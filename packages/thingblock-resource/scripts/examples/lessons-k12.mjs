// Wait for one full press of the SW button (press, then release) so one press counts once.
const onePress = () => [
  note('Đợi em bấm, rồi đợi em nhả tay. Giữ nút lâu cũng chỉ tính một lần.', waitUntil(pressed())),
  waitUntil(not(pressed())),
  wait(0.05),
]

