// Drive one wheel with a signed speed: the motor block takes 0..100, so the sign picks the direction.
const driveWheel = (m, name) =>
  ifElse(gt(v(name), 0), [motor(m, 'forward', v(name))], [motor(m, 'backward', sub(0, v(name)))])

// Zero a stick value inside the dead zone so a released stick does not creep.
const deadZone = (name, size) => ifThen(lt(mathop('abs', v(name)), size), set(name, 0))

